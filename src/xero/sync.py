"""Realize a topic directory from its topic.toml, or report how it drifts.

``sync(topic, fix=True)`` creates what is missing and repairs what is safely
repairable (wrong symlinks).  It never deletes or replaces real files or
directories: those are reported as drift for the user to resolve.
``sync(topic, fix=False)`` only reports.
"""

from __future__ import annotations

import os
from dataclasses import dataclass
from pathlib import Path

from . import gitops, view
from .topic import Entry, Topic
from .util import relsymlink, run

ENVRC_TEMPLATE = """\
# Generated by xero -- do not edit; regenerated by 'xero sync'.
# Run-time environment of topic '{topic}' in Spack env '{env}'.
watch_file {topic_rel} {area_rel}
eval "$(xero env --shell bash -t {topic} -e {env})"
"""


@dataclass
class Note:
    """One sync finding.  level: "fix" (was repaired) or "drift" (needs a human)."""

    level: str
    path: Path
    message: str

    def __str__(self) -> str:
        tag = "fixed" if self.level == "fix" else "DRIFT"
        return f"{tag}: {self.path}: {self.message}"


class Syncer:
    def __init__(self, topic: Topic, fix: bool) -> None:
        self.topic = topic
        self.area = topic.area
        self.fix = fix
        self.notes: list[Note] = []

    def note(self, level: str, path: Path, message: str) -> None:
        if level == "fix" and not self.fix:
            level = "drift"
        self.notes.append(Note(level, path, message))

    # --- primitives -----------------------------------------------------------

    def dir(self, path: Path) -> None:
        if path.is_dir():
            return
        if path.exists() or path.is_symlink():
            self.note("drift", path, "expected a directory")
            return
        self.note("fix", path, "missing directory")
        if self.fix:
            path.mkdir(parents=True)

    def link(self, link: Path, target: Path, allow_real: bool = False) -> None:
        """Ensure *link* is a relative symlink to *target*."""
        rel = os.path.relpath(target, link.parent)
        if link.is_symlink():
            if os.readlink(link) == rel:
                if not link.exists():
                    self.note("drift", link, f"dangling symlink to {rel}")
                return
            self.note("fix", link, f"symlink pointed to {os.readlink(link)}, want {rel}")
        elif link.exists():
            if not allow_real:
                self.note("drift", link, f"is a real file/directory, want symlink to {rel}")
            return
        else:
            self.note("fix", link, f"missing symlink to {rel}")
        if self.fix:
            relsymlink(link, target)

    # --- whole topic ------------------------------------------------------------

    def run(self) -> list[Note]:
        t = self.topic
        self.dir(t.source_dir)
        self.dir(t.refs_dir)
        # CMakeLists.txt: a symlink to the shared super-build file, unless the
        # topic overrides it with a real file.
        if any(t.builder_name(e) == "superbuild" for e in t.envs):
            self.link(t.source_dir / "CMakeLists.txt", self.area.superbuild_file, allow_real=True)

        for ent in t.sources.values():
            self.entry(ent)
        for ent in t.refs.values():
            self.entry(ent)
        self.strays(t.source_dir, set(t.sources) | {"CMakeLists.txt"})
        self.strays(t.refs_dir, set(t.refs))

        for env in t.envs:
            self.env(env)
        return self.notes

    def strays(self, base: Path, known: set[str]) -> None:
        if not base.is_dir():
            return
        for p in sorted(base.iterdir()):
            if p.name not in known:
                self.note("drift", p, "not described in topic.toml")

    def entry(self, ent: Entry) -> None:
        path = self.topic.entry_path(ent)
        if ent.mode == "link":
            wt = self.area.branch_path(ent.repo, ent.ref)
            self.worktree(ent, wt)
            self.link(path, wt)
        elif ent.mode == "clone":
            self.clone(ent, path)
        else:  # dir
            target = self.topic.link_target(ent)
            if target is None:
                self.dir(path)
            else:
                if not target.exists():
                    self.note("drift", target, f"[{ent.section}.{ent.name}] path does not exist")
                self.link(path, target)

    def worktree(self, ent: Entry, wt: Path) -> None:
        if wt.exists():
            ok, actual = gitops.head_matches(wt, ent.ref)
            if not ok:
                self.note("drift", wt, f"worktree has {actual} checked out, want {ent.ref}")
            return
        repo = self.area.repo_path(ent.repo)
        if not repo.is_dir():
            self.note("drift", wt, f"no repo '{ent.repo}' to make worktree from; see 'xero repo add'")
            return
        self.note("fix", wt, f"missing worktree of {ent.repo} {ent.ref}")
        if self.fix:
            gitops.add_worktree(repo, wt, ent.ref, submodules=ent.submodules)

    def clone(self, ent: Entry, path: Path) -> None:
        if path.is_symlink():
            self.note("drift", path, "is a symlink, want a full clone")
            return
        if path.exists():
            if not gitops.is_git(path):
                self.note("drift", path, "is not a git clone")
                return
            ok, actual = gitops.head_matches(path, ent.ref)
            if not ok:
                self.note("drift", path, f"clone has {actual} checked out, want {ent.ref}")
            return
        repo = self.area.repo_path(ent.repo)
        if not repo.is_dir():
            self.note("drift", path, f"no repo '{ent.repo}' to clone from; see 'xero repo add'")
            return
        self.note("fix", path, f"missing clone of {ent.repo} {ent.ref}")
        if not self.fix:
            return
        kind = gitops.ensure_local_branch(repo, ent.ref)
        # Clone from the local bare repo (fast, hard-linked), then aim origin at
        # the upstream and keep the bare repo reachable as remote "xero".
        run(["git", "clone", "-q", "--origin", "xero", repo, path])
        rems = self.area.repo_remotes(ent.repo) or gitops.remotes(repo)
        for name, url in rems.items():
            run(["git", "remote", "add", name, url], cwd=path)
        if kind == "branch":
            run(["git", "checkout", "-q", ent.ref], cwd=path)
            # Track the same upstream the bare repo's branch tracks.
            remote = gitops.git_out("config", f"branch.{ent.ref}.remote", cwd=repo)
            merge = gitops.git_out("config", f"branch.{ent.ref}.merge", cwd=repo)
            if remote in rems and merge:
                run(["git", "config", f"branch.{ent.ref}.remote", remote], cwd=path)
                run(["git", "config", f"branch.{ent.ref}.merge", merge], cwd=path)
        else:
            run(["git", "checkout", "-q", "--detach", ent.ref], cwd=path)
        if ent.submodules:
            gitops.init_submodules(path)

    def env(self, env: str) -> None:
        t = self.topic
        root = t.env_root(env)
        self.dir(root)
        self.link(root / "source", t.source_dir)
        msg = view.ensure(t, env, self.fix) if root.is_dir() else None
        if msg:
            self.note("fix", root / "view", msg)
        if not view.wanted(t, env):
            self.link(root / "view", self.area.env_dir(env) / "view")
        for sub in ("build", "install", "run"):
            self.dir(t.env_root(env) / sub)
        envrc = t.run_dir(env) / ".envrc"
        text = ENVRC_TEMPLATE.format(
            topic=t.name,
            env=env,
            topic_rel=os.path.relpath(t.file, t.run_dir(env)),
            area_rel=os.path.relpath(self.area.file, t.run_dir(env)),
        )
        if envrc.is_file() and envrc.read_text() == text:
            return
        self.note("fix", envrc, "missing or outdated .envrc")
        if self.fix and t.run_dir(env).is_dir():
            envrc.write_text(text)


def sync(topic: Topic, fix: bool = True) -> list[Note]:
    return Syncer(topic, fix).run()
